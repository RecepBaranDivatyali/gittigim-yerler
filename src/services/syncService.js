function stripUndefinedDeep(value) {
  if (value === undefined || value === null) return null;
  if (Array.isArray(value)) {
    return value.map(item => stripUndefinedDeep(item));
  }
  if (typeof value === 'object') {
    if (value.constructor && value.constructor.name !== 'Object') {
      return value;
    }
    const clean = {};
    for (const [k, v] of Object.entries(value)) {
      if (v !== undefined) {
        clean[k] = stripUndefinedDeep(v);
      }
    }
    return clean;
  }
  return value;
}

function sanitizeVisits(visitsObj) {
  if (!visitsObj || typeof visitsObj !== 'object') return {};
  const cleaned = { ...visitsObj };
  for (const k in cleaned) {
    if (cleaned[k]) {
      if (isAutoGeneratedNote(cleaned[k].notes)) {
        cleaned[k] = { ...cleaned[k], notes: '' };
      }
      if (cleaned[k].journal && isAutoGeneratedNote(cleaned[k].journal.text)) {
        cleaned[k] = { ...cleaned[k], journal: { ...cleaned[k].journal, text: '' } };
      }
    }
  }
  return cleaned;
}

let syncStatus = navigator.onLine ? 'synced' : 'offline';
let lastSyncTime = null;
let lastSyncError = null;
let syncTimeout = null;
// Cloud document ID that was successfully read (or confirmed empty) in this session.
// Full-document overwrites are only allowed after hydration so an empty local state can never wipe cloud data.
let cloudHydratedFor = null;
const statusListeners = new Set();

export function getSyncStatus() {
  return {
    status: syncStatus, // 'synced' | 'syncing' | 'offline' | 'error' | 'local'
    lastSyncTime,
    lastSyncError,
    error: lastSyncError,
    isOnline: navigator.onLine
  };
}

export function cancelPendingCloudSync() {
  if (syncTimeout) {
    clearTimeout(syncTimeout);
    syncTimeout = null;
  }
}

export function onSyncStatusChange(callback) {
  if (typeof callback === 'function') {
    statusListeners.add(callback);
    callback(getSyncStatus());
    return () => statusListeners.delete(callback);
  }
  return () => {};
}

function notifyStatus(newStatus, error = null) {
  syncStatus = newStatus;
  lastSyncError = error;
  if (newStatus === 'synced') {
    lastSyncTime = new Date();
    lastSyncError = null;
  }
  const current = getSyncStatus();
  statusListeners.forEach(cb => {
    try { cb(current); } catch (e) { console.error('Sync status listener error:', e); }
  });
}

// Global Online / Offline event listeners
if (typeof window !== 'undefined') {
  window.addEventListener('online', () => {
    notifyStatus('syncing');
    queueCloudSync(true);
  });
  window.addEventListener('offline', () => {
    notifyStatus('offline');
  });
}

/**
 * Get the current active user identifier for Firestore document
 */
export function getCurrentUserIdentifier() {
  try {
    const pStr = localStorage.getItem('gv_profile') || sessionStorage.getItem('gv_profile');
    if (pStr) {
      const p = JSON.parse(pStr);
      if (p?.isGuest) return null;
      if (auth?.currentUser?.uid) return auth.currentUser.uid;
      if (p?.uid && !String(p.uid).startsWith('guest_')) return p.uid;
      if (p && p.username) {
        return 'user_' + p.username.trim().toLowerCase().replace(/[^a-z0-9_]/g, '');
      }
    }
  } catch {}
  if (auth?.currentUser?.uid) {
    return auth.currentUser.uid;
  }
  return null;
}

/**
 * Gather all local storage state to pack into cloud document
 */
export function getLocalDataPayload() {
  let worldVisits = {};
  let turkeyVisits = {};
  let worldCities = [];
  let userVisas = [];
  let userPlaces = {};
  let notes = {};
  let ratings = {};
  let bucketRanks = [];
  let airlines = {};
  let aircraft = {};
  let profile = { username: 'Gezgin', avatar: '🧭' };
  let homeCountry = 'TR';
  let unlockedAchievements = [];

  try {
    try { worldVisits = JSON.parse(localStorage.getItem('gittigim_yerler_world_v2') || '{}'); } catch { worldVisits = {}; }
    try { turkeyVisits = JSON.parse(localStorage.getItem('gittigim_yerler_turkey_v2') || '{}'); } catch { turkeyVisits = {}; }
    try { worldCities = JSON.parse(localStorage.getItem('gittigim_yerler_cities_v2') || '[]'); } catch { worldCities = []; }
    try { userVisas = JSON.parse(localStorage.getItem('gv_user_visas_v1') || '[]'); } catch { userVisas = []; }
    try { userPlaces = JSON.parse(localStorage.getItem('gittigim_yerler_user_places_v1') || '{}'); } catch { userPlaces = {}; }
    try { notes = JSON.parse(localStorage.getItem('gittigim_yerler_country_notes_v1') || '{}'); } catch { notes = {}; }
    try { ratings = JSON.parse(localStorage.getItem('gittigim_yerler_country_ratings_v1') || '{}'); } catch { ratings = {}; }
    try { bucketRanks = JSON.parse(localStorage.getItem('gittigim_yerler_bucket_ranks_v1') || '[]'); } catch { bucketRanks = []; }
    try {
      const parsedAirlines = JSON.parse(localStorage.getItem('gittigim_yerler_airlines_v1') || '{}');
      airlines = (parsedAirlines && typeof parsedAirlines === 'object' && !Array.isArray(parsedAirlines)) ? parsedAirlines : {};
    } catch { airlines = {}; }
    try {
      const parsedAircraft = JSON.parse(localStorage.getItem('gittigim_yerler_aircraft_v1') || '{}');
      aircraft = (parsedAircraft && typeof parsedAircraft === 'object' && !Array.isArray(parsedAircraft)) ? parsedAircraft : {};
    } catch { aircraft = {}; }
    homeCountry = localStorage.getItem('gv_home_country') || 'TR';

    try {
      const unRaw = localStorage.getItem('gv_unlocked_achievements');
      if (unRaw) unlockedAchievements = JSON.parse(unRaw);
    } catch {}

    const pStr = localStorage.getItem('gv_profile') || sessionStorage.getItem('gv_profile');
    if (pStr) profile = JSON.parse(pStr);
  } catch (err) {
    console.warn('Error reading local data payload for cloud sync:', err);
  }

  worldVisits = sanitizeVisits(worldVisits);
  turkeyVisits = sanitizeVisits(turkeyVisits);
  if (notes && typeof notes === 'object') {
    const cleanN = {};
    for (const k in notes) {
      if (!isAutoGeneratedNote(notes[k])) {
        cleanN[k] = notes[k];
      }
    }
    notes = cleanN;
  }

  const cleanUsername = (profile.username || 'gezgin').trim().toLowerCase().replace(/[^a-z0-9_]/g, '');
  const cleanEmail = String(profile.email || auth?.currentUser?.email || '').trim().toLowerCase() || null;

  return {
    userId: getCurrentUserIdentifier(),
    email: cleanEmail,
    username: cleanUsername,
    displayName: profile.username || 'Gezgin',
    avatar: profile.avatar || '🧭',
    photoUrl: profile.photoUrl || null,
    bio: profile.bio || '',
    homeCountry,
    stats: {
      worldCountryCount: Object.keys(worldVisits).filter(k => !k.includes('::') && worldVisits[k]?.status === 'visited').length,
      turkeyCount: Object.keys(turkeyVisits).filter(k => turkeyVisits[k]?.status === 'visited').length,
      worldCityCount: Array.isArray(worldCities) ? worldCities.length : 0,
      visasCount: Array.isArray(userVisas) ? userVisas.length : 0
    },
    worldVisits,
    turkeyVisits,
    worldCities,
    userVisas,
    userPlaces,
    notes,
    ratings,
    bucketRanks,
    airlines,
    aircraft,
    unlockedAchievements,
    clientUpdatedAt: new Date().toISOString()
  };
}

/**
 * Debounced queue function to sync data to Firestore.
 * Automatically handles offline writes (Firestore caches into IndexedDB).
 */
export function queueCloudSync(force = false) {
  if (syncTimeout) {
    clearTimeout(syncTimeout);
    syncTimeout = null;
  }

  const doSync = async () => {
    if (typeof auth?.authStateReady === 'function') {
      try { await auth.authStateReady(); } catch {}
    }
    const userDocId = getCurrentUserIdentifier();
    if (!userDocId) {
      // User is not logged in yet or guest, local storage remains active
      notifyStatus('local');
      return;
    }

    // Check if user is authenticated with Firebase Auth
    const isFirebaseAuthed = Boolean(auth?.currentUser);
    if (!isFirebaseAuthed) {
      // User is operating with a local profile without an active Firebase Auth session.
      // Data is safely stored in localStorage. Defer cloud write without throwing error.
      console.info('Cloud sync deferred: Local profile active, no Firebase Auth session.');
      notifyStatus('local');
      return;
    }

    if (!navigator.onLine) {
      notifyStatus('offline');
      return;
    } else {
      notifyStatus('syncing');
    }

    try {
      const payload = getLocalDataPayload();
      const userRef = doc(db, 'users', userDocId);

      // Full overwrite (so deleted map keys don't resurrect) ONLY after this user's cloud doc was hydrated this session;
      // otherwise merge to avoid wiping cloud data with an empty/partial local state.
      const cleanUserLower = payload.username ? payload.username.trim().toLowerCase() : '';
      const docData = {
        ...payload,
        userId: userDocId,
        username_lowercase: cleanUserLower,
        serverUpdatedAt: serverTimestamp()
      };
      const cleanedDocData = stripUndefinedDeep(docData);

      if (cloudHydratedFor === userDocId) {
        await setDoc(userRef, cleanedDocData);
      } else {
        await setDoc(userRef, cleanedDocData, { merge: true });
      }

      // Also register or update username directory for global friend searches (in isolated try/catch so it can never fail user data sync)
      if (cleanUserLower) {
        try {
          const usernameRef = doc(db, 'usernames', cleanUserLower);
          let canClaimUsername = true;
          try {
            const existingUsernameSnap = await getDoc(usernameRef);
            if (existingUsernameSnap.exists()) {
              const ownerUid = existingUsernameSnap.data()?.uid;
              if (ownerUid && ownerUid !== userDocId && ownerUid !== ('user_' + cleanUserLower)) {
                canClaimUsername = false;
              }
            }
          } catch {}
          if (canClaimUsername) {
            await setDoc(usernameRef, stripUndefinedDeep({
              uid: userDocId,
              username: cleanUserLower,
              displayName: payload.displayName || payload.username,
              avatar: payload.avatar,
              photoUrl: payload.photoUrl,
              stats: payload.stats,
              updatedAt: serverTimestamp()
            }), { merge: true });
          }
        } catch (uErr) {
          console.warn('Username directory sync warning (non-fatal):', uErr);
        }
      }

      if (navigator.onLine) {
        notifyStatus('synced');
      } else {
        notifyStatus('offline');
      }
    } catch (err) {
      console.warn('Cloud sync error (stored in offline cache if available):', err);
      const errMsg = err?.message || String(err);
      if (!navigator.onLine) {
        notifyStatus('offline');
      } else {
        notifyStatus('error', errMsg);
      }
    }
  };

  if (force) {
    return doSync();
  }

  // 1200ms debounce to prevent burst network queries during rapid clicks
  syncTimeout = setTimeout(doSync, 1200);
}

/**
 * Fetch cloud data for user and merge into LocalStorage
 */
export async function fetchAndMergeUserDataFromCloud(userIdOrUsername = null) {
  if (typeof auth?.authStateReady === 'function') {
    try { await auth.authStateReady(); } catch {}
  }
  const authUid = auth?.currentUser?.uid || null;
  const currentId = getCurrentUserIdentifier();
  const candidateIds = [];
  if (authUid) {
    // If authenticated via Firebase, authUid is the ONLY authoritative candidate
    candidateIds.push(authUid);
  } else {
    if (currentId && !candidateIds.includes(currentId)) {
      candidateIds.push(currentId);
    }
    if (userIdOrUsername) {
      const raw = String(userIdOrUsername).trim();
      if (raw && !candidateIds.includes(raw)) candidateIds.push(raw);
      const clean = raw.toLowerCase().replace(/[^a-z0-9_]/g, '');
      if (clean) {
        const legacyId = 'user_' + clean;
        if (!candidateIds.includes(legacyId)) candidateIds.push(legacyId);
      }
    }
  }

  if (candidateIds.length === 0) return null;

  try {
    notifyStatus('syncing');
    let data = null;
    let hadReadError = false;

    // 1. Check candidate user document IDs in priority order
    for (const cid of candidateIds) {
      try {
        const snap = await getDoc(doc(db, 'users', cid));
        if (snap.exists()) {
          data = snap.data();
          break;
        }
      } catch {
        hadReadError = true;
      }
    }

    // 2. Fallback: look up by verified email ONLY if not authenticated with Firebase Auth
    if (!data && !authUid) {
      let profileEmail = '';
      try {
        const pStr = localStorage.getItem('gv_profile') || sessionStorage.getItem('gv_profile');
        if (pStr) {
          const p = JSON.parse(pStr);
          if (p?.email) profileEmail = String(p.email).trim().toLowerCase();
        }
      } catch {}
      if (profileEmail && !profileEmail.endsWith('@oauth.gezginapp.com') && !profileEmail.endsWith('@privaterelay.gezginapp.com')) {
        try {
          const eq = query(collection(db, 'users'), where('email', '==', profileEmail), limit(1));
          const eqSnap = await getDocs(eq);
          if (!eqSnap.empty) {
            data = eqSnap.docs[0].data();
          }
        } catch {}
      }
      if (!data && userIdOrUsername) {
        const clean = String(userIdOrUsername).trim().toLowerCase().replace(/[^a-z0-9_]/g, '');
        if (clean) {
          try {
            const uSnap = await getDoc(doc(db, 'usernames', clean));
            if (uSnap.exists()) {
              const uData = uSnap.data();
              const targetUid = uData?.uid;
              if (targetUid) {
                const targetSnap = await getDoc(doc(db, 'users', targetUid));
                if (targetSnap.exists()) data = targetSnap.data();
              }
            }
          } catch {}
        }
      }
    }

    // Security guard: Ensure cloud document strictly matches the active Firebase Auth UID
    if (data && authUid) {
      const docOwner = data.userId || data.uid;
      if (docOwner && docOwner !== authUid) {
        console.warn('Security guard: Cloud document owner mismatch, ignoring foreign data.');
        data = null;
      }
    }

    if (data) {
      // Merge into local storage
      if (data.worldVisits && typeof data.worldVisits === 'object') {
        const localWorld = JSON.parse(localStorage.getItem('gittigim_yerler_world_v2') || '{}');
        const mergedWorld = sanitizeVisits({ ...data.worldVisits, ...localWorld });
        try { localStorage.setItem('gittigim_yerler_world_v2', JSON.stringify(mergedWorld)); } catch(e) { console.warn('Storage write failed:', e); }
      }

      if (data.turkeyVisits && typeof data.turkeyVisits === 'object') {
        const localTR = JSON.parse(localStorage.getItem('gittigim_yerler_turkey_v2') || '{}');
        const mergedTR = sanitizeVisits({ ...data.turkeyVisits, ...localTR });
        try { localStorage.setItem('gittigim_yerler_turkey_v2', JSON.stringify(mergedTR)); } catch(e) { console.warn('Storage write failed:', e); }
      }

      if (Array.isArray(data.worldCities)) {
        const localCities = JSON.parse(localStorage.getItem('gittigim_yerler_cities_v2') || '[]');
        const mergedCities = Array.from(new Set([...data.worldCities, ...(Array.isArray(localCities) ? localCities : [])]));
        try { localStorage.setItem('gittigim_yerler_cities_v2', JSON.stringify(mergedCities)); } catch(e) { console.warn('Storage write failed:', e); }
      }

      // User Visas: Strict account isolation. Cloud document is source of truth.
      const cloudVisas = Array.isArray(data.userVisas) ? data.userVisas : [];
      try {
        localStorage.setItem('gv_user_visas_v1', JSON.stringify(cloudVisas));
      } catch(e) { console.warn('Storage write failed:', e); }

      // Visa Overrides
      const cloudVisaOverrides = (data.visaOverrides && typeof data.visaOverrides === 'object') ? data.visaOverrides : {};
      try {
        localStorage.setItem('gv_visa_overrides', JSON.stringify(cloudVisaOverrides));
      } catch(e) {}

      // Passport Type
      if (data.passportType && typeof data.passportType === 'string') {
        try { localStorage.setItem('gv_passport_type', data.passportType); } catch {}
      } else {
        try { localStorage.setItem('gv_passport_type', 'bordro'); } catch {}
      }

      // Upcoming Trip
      if (data.upcomingTrip && typeof data.upcomingTrip === 'object') {
        try { localStorage.setItem('gv_upcoming_trip', JSON.stringify(data.upcomingTrip)); } catch {}
      } else {
        try { localStorage.removeItem('gv_upcoming_trip'); } catch {}
      }

      // User Places
      const cloudPlaces = (data.userPlaces && typeof data.userPlaces === 'object') ? data.userPlaces : {};
      try { localStorage.setItem('gittigim_yerler_user_places_v1', JSON.stringify(cloudPlaces)); } catch(e) { console.warn('Storage write failed:', e); }

      // Country Notes
      const cloudNotes = (data.notes && typeof data.notes === 'object') ? data.notes : {};
      const cleanedNotes = {};
      for (const k in cloudNotes) {
        if (!isAutoGeneratedNote(cloudNotes[k])) {
          cleanedNotes[k] = cloudNotes[k];
        }
      }
      try { localStorage.setItem('gittigim_yerler_country_notes_v1', JSON.stringify(cleanedNotes)); } catch(e) { console.warn('Storage write failed:', e); }

      // Country Ratings
      const cloudRatings = (data.ratings && typeof data.ratings === 'object') ? data.ratings : {};
      try { localStorage.setItem('gittigim_yerler_country_ratings_v1', JSON.stringify(cloudRatings)); } catch(e) { console.warn('Storage write failed:', e); }

      // Bucket Ranks
      const cloudBucket = Array.isArray(data.bucketRanks) ? data.bucketRanks : [];
      try { localStorage.setItem('gittigim_yerler_bucket_ranks_v1', JSON.stringify(cloudBucket)); } catch {}

      // Airlines & Aircraft
      const cloudAirlines = (data.airlines && typeof data.airlines === 'object' && !Array.isArray(data.airlines)) ? data.airlines : {};
      try { localStorage.setItem('gittigim_yerler_airlines_v1', JSON.stringify(cloudAirlines)); } catch {}

      const cloudAircraft = (data.aircraft && typeof data.aircraft === 'object' && !Array.isArray(data.aircraft)) ? data.aircraft : {};
      try { localStorage.setItem('gittigim_yerler_aircraft_v1', JSON.stringify(cloudAircraft)); } catch {}

      if (data.homeCountry && typeof data.homeCountry === 'string') {
        try { localStorage.setItem('gv_home_country', data.homeCountry); } catch {}
      }

      // Immediately silence and hydrate achievements for cloud-synced data so old achievements never trigger unlock toasts on login
      if (Array.isArray(data.unlockedAchievements) && data.unlockedAchievements.length > 0) {
        const localUn = JSON.parse(localStorage.getItem('gv_unlocked_achievements') || '[]');
        const mergedUn = Array.from(new Set([...data.unlockedAchievements, ...localUn]));
        try { localStorage.setItem('gv_unlocked_achievements', JSON.stringify(mergedUn)); } catch {}
        silenceAndHydrateUnlockedAchievements(mergedUn);
      } else {
        silenceAndHydrateUnlockedAchievements();
      }

      cloudHydratedFor = getCurrentUserIdentifier();
      notifyStatus('synced');
      return data;
    }

    if (!hadReadError) {
      cloudHydratedFor = getCurrentUserIdentifier();
      notifyStatus('synced');
    }
  } catch (err) {
    console.warn('Could not fetch cloud data, using offline state:', err);
    notifyStatus(navigator.onLine ? 'error' : 'offline');
  }
  return null;
}

/**
 * Search registered travelers in Firestore
 */
export async function searchCloudTravelers(searchQuery) {
  if (!searchQuery || typeof searchQuery !== 'string') return [];
  const cleanQ = searchQuery.trim().toLowerCase().replace(/^@/, '');
  if (!cleanQ || cleanQ.length < 2) return [];
  if (!db) return [];

  try {
    const resultsMap = new Map();

    // 1. Direct exact username lookup
    try {
      const exactSnap = await getDoc(doc(db, 'usernames', cleanQ));
      if (exactSnap.exists()) {
        const u = exactSnap.data();
        if (u?.username) resultsMap.set(u.username.toLowerCase(), u);
      }
    } catch {}

    // 2. Prefix query in usernames collection (returns all users whose username starts with query)
    try {
      const qPrefix = query(
        collection(db, 'usernames'),
        where('username', '>=', cleanQ),
        where('username', '<=', cleanQ + '\uf8ff'),
        limit(30)
      );
      const snapshot = await getDocs(qPrefix);
      snapshot.forEach(docSnap => {
        const u = docSnap.data();
        if (u?.username) {
          resultsMap.set(u.username.toLowerCase(), u);
        }
      });
    } catch {}

    // 3. Broad scan for displayName or partial contains matches
    if (resultsMap.size < 10) {
      try {
        const qBroad = query(collection(db, 'usernames'), limit(50));
        const broadSnap = await getDocs(qBroad);
        broadSnap.forEach(docSnap => {
          const u = docSnap.data();
          if (u && (u.username?.toLowerCase().includes(cleanQ) || u.displayName?.toLowerCase().includes(cleanQ))) {
            resultsMap.set(u.username.toLowerCase(), u);
          }
        });
      } catch {}
    }

    return Array.from(resultsMap.values());
  } catch (err) {
    console.warn('Error querying Firestore for travelers:', err);
    return [];
  }
}

/**
 * Strict Global Username Uniqueness check in Firestore
 */
export async function isUsernameAvailableInCloud(username, currentUserId = null) {
  if (!username || typeof username !== 'string') return false;
  const clean = username.trim().toLowerCase().replace(/^@/, '');
  if (!clean || clean.length < 3) return false;
  if (!db) return true;

  try {
    // 1. Check usernames directory (lowercase key)
    const usernameSnap = await getDoc(doc(db, 'usernames', clean));
    if (usernameSnap.exists()) {
      const data = usernameSnap.data();
      if (currentUserId && data?.uid === currentUserId) {
        return true; // Owned by the current user
      }
      return false; // Already taken by another user
    }

    // 2. Check users collection
    const userQ = query(
      collection(db, 'users'),
      where('username_lowercase', '==', clean),
      limit(1)
    );
    const userSnap = await getDocs(userQ);
    if (!userSnap.empty) {
      const matchDoc = userSnap.docs[0];
      if (currentUserId && matchDoc.id === currentUserId) {
        return true;
      }
      return false;
    }

    return true;
  } catch (err) {
    console.warn('Could not verify username uniqueness in cloud:', err);
    return true; // Fallback to allowing if network check fails
  }
}

/**
 * Fetch a full public profile of a traveler by username
 */
export async function getCloudTravelerProfile(username) {
  if (!username) return null;
  const clean = username.trim().toLowerCase().replace(/^@/, '');
  try {
    const usernameSnap = await getDoc(doc(db, 'usernames', clean));
    if (usernameSnap.exists()) {
      const uData = usernameSnap.data();
      const userSnap = await getDoc(doc(db, 'users', uData.uid));
      if (userSnap.exists()) {
        return userSnap.data();
      }
      return uData;
    }
  } catch (err) {
    console.warn('Error fetching traveler cloud profile:', err);
  }
  return null;
}

/**
 * Permanently delete the user's cloud Firestore documents and Firebase Auth account (Apple Guideline 5.1.1(v))
 */
export async function deleteUserCloudAccountData() {
  if (syncTimeout) {
    clearTimeout(syncTimeout);
    syncTimeout = null;
  }

  let cleanUsername = '';
  try {
    const pStr = localStorage.getItem('gv_profile') || sessionStorage.getItem('gv_profile');
    if (pStr) {
      const p = JSON.parse(pStr);
      if (p?.username) {
        cleanUsername = p.username.trim().toLowerCase().replace(/[^a-z0-9_]/g, '');
      }
    }
  } catch {}

  const userDocId = getCurrentUserIdentifier();

  // 1. Delete Firestore documents if online
  if (db) {
    try {
      const promises = [];
      if (userDocId) {
        promises.push(deleteDoc(doc(db, 'users', userDocId)).catch(() => {}));
      }
      if (cleanUsername) {
        promises.push(deleteDoc(doc(db, 'users', 'user_' + cleanUsername)).catch(() => {}));
        promises.push(deleteDoc(doc(db, 'usernames', cleanUsername)).catch(() => {}));
      }
      await Promise.allSettled(promises);
    } catch (e) {
      console.warn('Firestore account deletion error:', e);
    }
  }

  // 2. Remove from local community travelers directory
  if (cleanUsername) {
    for (const key of ['gv_community_travelers', 'gv_community_travelers_v1']) {
      try {
        const raw = localStorage.getItem(key);
        if (raw) {
          const list = JSON.parse(raw);
          if (Array.isArray(list)) {
            const filtered = list.filter(u => String(u.username || '').toLowerCase() !== cleanUsername);
            localStorage.setItem(key, JSON.stringify(filtered));
          }
        }
      } catch {}
    }
  }

  // 3. Delete Firebase Auth user if signed in, then signOut
  if (auth?.currentUser) {
    try {
      await deleteUser(auth.currentUser);
    } catch (e) {
      console.warn('Firebase Auth deleteUser notice:', e?.code || e?.message);
    }
  }
  if (auth) {
    try {
      await auth.signOut();
    } catch {}
  }
}
