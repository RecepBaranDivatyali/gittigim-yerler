export function getCountryDemographics(countryCode) {
  if (!countryCode) return { area: 100000, pop: 5000000 };
  const cleanCode = countryCode.toUpperCase();
  return WORLD_COUNTRY_DEMOGRAPHICS[cleanCode] || { area: 100000, pop: 5000000 };
}

export function calculateDemographicImpact(visitedCountryCodes = []) {
  const uniqueCodes = Array.from(new Set(visitedCountryCodes.filter(c => c && !c.includes('::'))));
  
  let totalArea = 0;
  let totalPop = 0;

  uniqueCodes.forEach(code => {
    const demo = getCountryDemographics(code);
    totalArea += demo.area;
    totalPop += demo.pop;
  });

  const landAreaPercent = ((totalArea / TOTAL_WORLD_LAND_AREA_KM2) * 100).toFixed(1);
  const populationPercent = ((totalPop / TOTAL_WORLD_POPULATION) * 100).toFixed(1);

  return {
    totalAreaKm2: totalArea,
    landAreaPercent: Math.min(100, parseFloat(landAreaPercent)),
    totalPopCount: totalPop,
    populationPercent: Math.min(100, parseFloat(populationPercent))
  };
}
