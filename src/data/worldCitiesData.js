// Generic Fallback helper to retrieve or search cities cleanly
export function getCitiesForCountry(countryCode, searchQuery = '') {
  const cities = COUNTRY_FULL_CITIES[countryCode] || [
    'Başkent ve Merkez Şehir', 'Tarihi Şehir', 'Sahil Şehri', 'Kültür Şehri'
  ];
  if (!searchQuery) return cities;
  const q = searchQuery.toLowerCase().trim();
  return cities.filter(c => c.toLowerCase().includes(q));
}
